-- Standardization per rules R014 (lowercase email), R015 (phone -> E.164-ish)
-- ERP full_name arrives as "Last, First" -- split into canonical first/last here
-- Validation flags computed per rules R009-R013 (see seed: column_rules)
--
-- bronze.erp_customers_raw is append-only (scripts/load_bronze.py lands every
-- full/incremental load as new rows, never overwrites) -- so this model first
-- collapses it down to current state, the single latest row per
-- source_record_id by _load_ts, before standardizing anything. A full load
-- only ever produces one row per key, so this is a no-op in that case.
--
-- Incremental materialization: see stg_crm_customers.sql's docstring --
-- identical pattern here (full-history scan on full-refresh/first run,
-- current-batch-only scan on a plain incremental run; is_deleted is
-- carried through unfiltered, filtered downstream in silver_all_staged.sql).
{{ config(materialized='incremental', unique_key='source_record_id', incremental_strategy='delete+insert') }}
with raw as (
    select * from {{ source('bronze', 'erp_customers_raw') }}
    {% if is_incremental() %}
    where _load_batch_id = '{{ latest_load_batch_id() }}'
    {% endif %}
),

latest as (
    select * exclude (_rn)
    from (
        select
            *,
            row_number() over (
                partition by source_record_id
                order by _load_ts desc, _load_batch_id desc
            ) as _rn
        from raw
    )
    where _rn = 1
),

standardized as (
    select
        source_system,
        source_record_id,
        coalesce(try_cast(is_deleted as boolean), false) as is_deleted,
        nullif(trim(regexp_replace({{ proper_case("split_part(full_name, ',', 2)") }}, '\s+', ' ')), '') as first_name,
        nullif(trim(regexp_replace({{ proper_case("split_part(full_name, ',', 1)") }}, '\s+', ' ')), '') as last_name,
        -- R014: lowercase email
        lower(nullif(trim(email_addr), '')) as email,
        -- R015: standardize phone to +1XXXXXXXXXX
        case
            when regexp_replace(coalesce(contact_phone, ''), '[^0-9]', '', 'g') != ''
            then '+1' || right(regexp_replace(contact_phone, '[^0-9]', '', 'g'), 10)
            else null
        end as phone,
        nullif(trim(addr1), '') as address_line1,
        nullif(trim(addr2), '') as address_line2,
        nullif(trim(city_code), '') as city,
        upper(nullif(trim(state_code), '')) as state_code,
        nullif(trim(postal_code), '') as postal_code,
        upper(nullif(trim(country_code), '')) as country_code,
        cast(null as date) as source_created_date,
        try_cast(last_updated as date) as source_modified_date
    from latest
)

select
    *,
    -- R009: full_name required (either side missing after split counts as missing).
    -- NOT generated by column_rule_flags(): full_name isn't a plain staged
    -- column, it's split into first_name/last_name above, so "is it missing"
    -- is a property of that split rather than a column_rules-style check on
    -- one column -- see column_rule_flags()'s docstring. Stays hand-written.
    (first_name is null or last_name is null) as err_missing_last_name,
    false as err_missing_first_name,
    -- Phase 2 (flexibility): email/phone/state_code/country_code (R010-R013)
    -- are generated straight from active bus_rules.column_rules rows at
    -- compile time -- see macros/column_rule_flags.sql.
    {{ column_rule_flags('ERP', ['email', 'phone', 'state_code', 'country_code']) }}
from standardized
